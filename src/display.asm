; LCD rendering uses one 32-cell write after the peer has been paused.
; Normal status changes are coalesced to at most about two updates/second.
TTYSTATUS TST UIUPDATE
        BEQ UISTATUSRET
        TST MENUACTIVE
        BNE UIREFRESH
        LDD $09
        SUBD UITIMER
        SUBD #40000
        BCS UISTATUSRET
        LDD $09
        STD UITIMER
        INC UIPERIOD
        LDAA UIPERIOD
        CMPA #12
        BCS UISTATUSRET
        BRA UIREFRESH
UISTATUSRET RTS
UIREFRESH PSHA
        PSHB
        PSHX
        JSR TTYQUIET
        LDX #LCDTEXT
        LDAA #32
UICLEARBUFFER STAA ,X
        INX
        CPX #LCDTEXT+32
        BNE UICLEARBUFFER
        LDX #LCDTEXT
        STX UIWRITEPTR
        TST MENUACTIVE
        BEQ UIONLINE
        JSR UIMENU
        JMP UICOMMIT
UIONLINE LDAB BAUDSEL
        JSR UIRATETEXT
        LDAA #32
        JSR UICHAR
        LDAB FRAMESEL
        JSR UIFRAMETEXT
        LDAA #32
        JSR UICHAR
        LDAB FLOWSEL
        JSR UIFLOWTEXT
        LDX #LCDTEXT+14
        STX UIWRITEPTR
        LDAA #'R'
        JSR UICHAR
        LDAA #'-'
        LDAB UIRX
        CMPB UIRXLAST
        BEQ UIRXMARK
        LDAA #'+'
UIRXMARK JSR UICHAR
        TST UIERROR
        BNE UIDISPLAYERROR
        TST PREVIEWSEL
        BEQ UISTATS
        LDX #PREVIEWBUF
        LDAB #16
UIPREVIEWCOPY LDAA ,X
        JSR UICHAR
        INX
        DECB
        BNE UIPREVIEWCOPY
        BRA UICOMMIT
UISTATS LDAA #'T'
        JSR UICHAR
        LDAA #'-'
        LDAB UITX
        CMPB UITXLAST
        BEQ UITXMARK
        LDAA #'+'
UITXMARK JSR UICHAR
        LDX #UIQUEUELABEL
        JSR UISTR
        LDAA RXHEAD
        SUBA RXTAIL
        JSR UIDEC3
        LDX #UIHOSTECHO
        TST ECHOSEL
        BEQ UIECHOINFO
        LDX #UILOCALECHO
UIECHOINFO JSR UISTR
        BRA UICOMMIT
UIDISPLAYERROR LDX #UIERRORPARITY
        LDAA UIERROR
        BITA #1
        BNE UIERRORREADY
        LDX #UIERRORFRAME
        BITA #2
        BNE UIERRORREADY
        LDX #UIERRORRXFULL
        BITA #4
        BNE UIERRORREADY
        LDX #UIERRORTXFULL
        BITA #8
        BNE UIERRORREADY
        LDX #UIERRORECHOFULL
        BITA #16
        BNE UIERRORREADY
        LDX #UIERRORTXWAIT
UIERRORREADY JSR UISTR
UICOMMIT LDX #LCDTEXT
        STX UITMPPTR
        LDX #LCDBUF
        STX UIWRITEPTR
        LDX UITMPPTR
        LDAB #32
UICOPYLCD LDAA ,X
        INX
        PSHX
        LDX UIWRITEPTR
        STAA ,X
        INX
        STX UIWRITEPTR
        PULX
        DECB
        BNE UICOPYLCD
        JSR LCDREDRAW
        CLRB
        LDAA UIRX
        CMPA UIRXLAST
        BEQ UIRXUNCHANGED
        INCB
UIRXUNCHANGED EQU *
        STAA UIRXLAST
        LDAA UITX
        CMPA UITXLAST
        BEQ UITXUNCHANGED
        INCB
UITXUNCHANGED EQU *
        STAA UITXLAST
        STAB UIUPDATE            ; one extra update clears transient + marks
        CLR UIPERIOD
        LDD $09
        STD UITIMER
        CLR TPRINTBUSY
        PULX
        PULB
        PULA
        RTS

UIMENU LDAB MENUITEM
        ASLB
        LDX #UIMENULABELS
        ABX
        LDX ,X
        JSR UISTR
        LDAB MENUITEM
        LDX #MENUEDIT
        ABX
        LDAA ,X
        TSTB
        BEQ UIMENURATE
        CMPB #1
        BEQ UIMENUFRAME
        CMPB #2
        BEQ UIMENUFLOW
        CMPB #3
        BEQ UIMENURETURN
        TAB
        ASLB
        LDX #UIBOOLEANS
        BRA UIMENUVALUE
UIMENURATE TAB
        JSR UIRATETEXT
        BRA UIMENUFOOT
UIMENUFRAME TAB
        JSR UIFRAMETEXT
        BRA UIMENUFOOT
UIMENUFLOW TAB
        JSR UIFLOWTEXT
        BRA UIMENUFOOT
UIMENURETURN TAB
        ASLB
        LDX #UIRETURNVALUES
UIMENUVALUE ABX
        LDX ,X
        JSR UISTR
UIMENUFOOT LDX #LCDTEXT+22
        STX UIWRITEPTR
        LDX #UIFOOTER
        LDAA UIERROR
        BITA #32
        BEQ UISTR
        LDX #UIFOOTBUSY
        BRA UISTR

UIRATETEXT ASLB
        LDX #UIRATES
        BRA UITABLETEXT
UIFRAMETEXT ASLB
        LDX #UIFRAMES
        BRA UITABLETEXT
UIFLOWTEXT ASLB
        LDX #UIFLOWS
UITABLETEXT ABX
        LDX ,X
UISTR LDAA ,X
        BEQ UISTRRET
        INX
        JSR UICHAR
        BRA UISTR
UISTRRET RTS
UICHAR PSHX
        LDX UIWRITEPTR
        STAA ,X
        INX
        STX UIWRITEPTR
        PULX
        RTS
UIDEC3 LDAB #'0'
UIDECHUNDREDS CMPA #100
        BCS UIDEC100DONE
        SUBA #100
        INCB
        BRA UIDECHUNDREDS
UIDEC100DONE PSHA
        TBA
        JSR UICHAR
        PULA
        LDAB #'0'
UIDECTENS CMPA #10
        BCS UIDEC10DONE
        SUBA #10
        INCB
        BRA UIDECTENS
UIDEC10DONE PSHA
        TBA
        JSR UICHAR
        PULA
        ADDA #'0'
        JMP UICHAR

; Preview only received text. Local keystrokes stay off the LCD.
UIPREVIEW TST PREVIEWSEL
        BEQ UIPREVIEWRET
        CMPA #13
        BNE UIPREVIEWCHAR
        LDAA #32
UIPREVIEWCHAR CMPA #32
        BCS UIPREVIEWRET
        CMPA #126
        BHI UIPREVIEWRET
        PSHB
        PSHX
        PSHA
        LDX #PREVIEWBUF
        LDAB #15
UIPREVSHIFT LDAA 1,X
        STAA ,X
        PSHB
        PSHX
        JSR TTYSERVICE           ; scrolling 16 cells must not block fast RX
        PULX
        PULB
        INX
        DECB
        BNE UIPREVSHIFT
        PULA
        STAA ,X
        LDAA #1
        STAA UIUPDATE
        PULX
        PULB
UIPREVIEWRET RTS

